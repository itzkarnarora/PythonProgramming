# Welcome to Band Name Generator

# Ask the user for the name of the city they were born in
cityName = input("What's the name of city you were born in? : \n")

# Ask the user for the name of their first pet
petName = input("What's your first pet's name? : \n")

# Combine the city and pet names to create a possible band name
print(f"Your band name could be {cityName} {petName}")
